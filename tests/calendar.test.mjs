import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import {webcrypto} from 'node:crypto';
const ctx = vm.createContext({crypto:webcrypto, TextDecoder, atob});
vm.runInContext(await readFile(new URL('../extension/calendar.js', import.meta.url), 'utf8'), ctx);
const ics = `BEGIN:VCALENDAR\r\nMETHOD:REQUEST\r\nBEGIN:VEVENT\r\nUID:test@example.com\r\nDTSTART;TZID="W. Europe Standard Time":20261027T110000\r\nDTEND;TZID="W. Europe Standard Time":20261027T113000\r\nSUMMARY:Review\\, costs\r\nDESCRIPTION:Join https://teams.microsoft.com/meet/123?\r\n p=example\\nNotes\r\nORGANIZER;CN="Host: Example":mailto:host@example.com\r\nATTENDEE;ROLE=REQ-PARTICIPANT:mailto:guest@example.com\r\nBEGIN:VALARM\r\nDESCRIPTION:Alarm text\r\nEND:VALARM\r\nEND:VEVENT\r\nEND:VCALENDAR`;
let event = ctx.TBCalendar.parse(ics)[0];
assert.equal(event.start.value, '2026-10-27T11:00:00');
assert.equal(event.start.timezone, 'W. Europe Standard Time');
assert.equal(event.end.value, '2026-10-27T11:30:00');
assert.equal(event.organizer.name, 'Host: Example');
assert.equal(event.title, 'Review, costs');
assert.equal(event.meeting_links[0], 'https://teams.microsoft.com/meet/123?p=example');
assert.ok(!event.description.includes('Alarm text'));
const calendar = lines => `BEGIN:VCALENDAR\nBEGIN:VEVENT\n${lines}\nEND:VEVENT\nEND:VCALENDAR`;
assert.equal(ctx.TBCalendar.parse(calendar('DTSTART:20261027T100000Z'))[0].start.timezone, 'UTC');
assert.equal(ctx.TBCalendar.parse(calendar('DTSTART:20261027T100000'))[0].start.floating, true);
event = ctx.TBCalendar.parse(calendar('DTSTART;VALUE=DATE:20261027\nDTEND;VALUE=DATE:20261028\nSTATUS:CANCELLED\nRRULE:FREQ=WEEKLY'))[0];
assert.equal(event.start.all_day, true); assert.equal(event.end.value, '2026-10-28');
assert.equal(event.status, 'CANCELLED'); assert.equal(event.recurrence.length, 1);
assert.throws(() => ctx.TBCalendar.parse('x'.repeat(256001)), /exceeds/);
assert.throws(() => ctx.TBCalendar.parse('BEGIN:VCALENDAR\nBEGIN:VEVENT'), /Incomplete/);
let root = {parts:[{contentType:'text/plain',body:'mail'},{contentType:'text/calendar',partName:'1.2',body:ics}]};
ctx.messenger = {messages:{getFull:async()=>root, getAttachmentFile:async()=>({size:ics.length,text:async()=>ics})}};
assert.equal((await ctx.TBCalendar.read(1)).events.length, 1);
delete root.parts[1].body;
assert.equal((await ctx.TBCalendar.read(1)).events.length, 1);
ctx.messenger.messages.getAttachmentFile = async()=>{throw new Error('unavailable');};
assert.equal((await ctx.TBCalendar.read(1)).warnings.length, 1);
const raw = 'Content-Type: multipart/alternative; boundary="example"\r\n\r\n--example\r\nContent-Type: text/calendar; charset=utf-8\r\nContent-Transfer-Encoding: base64\r\n\r\n' + Buffer.from(ics).toString('base64') + '\r\n--example--\r\n';
ctx.messenger.messages.getRaw = async()=>({size:raw.length,text:async()=>raw});
assert.equal((await ctx.TBCalendar.read(1)).events[0].start.value, '2026-10-27T11:00:00');
assert.equal(ctx.TBCalendar.rawCalendars('Content-Type: text/calendar\r\nContent-Transfer-Encoding: quoted-printable\r\n\r\n'+ics.replaceAll('=', '=3D'))[0],ics);
root = {parts:[{contentType:'message/rfc822',parts:[{contentType:'text/calendar',body:ics}]}]};
assert.equal((await ctx.TBCalendar.read(1)).events.length, 0);
root = {parts:[{contentType:'text/calendar',partName:'1.2',body:ics}]};
Object.assign(ctx.messenger.messages, {get:async()=>({id:1,date:'2026-10-01',subject:'Invite'}),listInlineTextParts:async()=>[{contentType:'text/plain',content:'Join meeting'}],getHeaders:async()=>({}),listAttachments:async()=>[]});
vm.runInContext(await readFile(new URL('../extension/core.js', import.meta.url), 'utf8'), ctx);
const message = await ctx.TBDirect.handle('read_message', {ref:ctx.TBDirect.summary({id:1,date:'2026-10-01'}).ref});
assert.equal(message.calendar.events[0].start.value, '2026-10-27T11:00:00');
assert.equal(message.text, 'Join meeting');
console.log('PASS: calendar MIME, attachment fallback, timezone preservation, folding, cancellations, recurrence and read_message integration.');
